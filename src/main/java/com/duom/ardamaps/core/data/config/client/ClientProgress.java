package com.duom.ardamaps.core.data.config.client;

import com.duom.ardamaps.ArdaMapsClient;
import com.duom.ardamaps.core.Client;
import com.duom.ardamaps.core.data.ExplorationState;
import com.duom.ardamaps.core.data.PlayerExploration;
import com.duom.ardamaps.core.data.config.Dimension;
import lombok.Getter;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.Serial;
import java.io.Serializable;
import java.util.*;

/**
 * Class representing the client's exploration progress, including per-dimension exploration states.
 * This class is serializable for persistence purposes.
 */
@Getter
public class ClientProgress implements Serializable {

    /** Class logger */
    private static final Logger LOGGER = LoggerFactory.getLogger(ClientProgress.class);

    @Serial
    private static final long serialVersionUID = 2L;

    /** Map of exploration key to per-dimension or per-range exploration state. */
    private final Map<String, PlayerExploration> explorationState = new HashMap<>();

    /** IDs of locations the player has visited */
    private final Set<String> visitedLocationIds = new HashSet<>();

    /**
     * Creates a shallow collection snapshot for serialization.
     *
     * @return A progress object whose maps/sets will not be concurrently mutated by the client tick.
     */
    public ClientProgress snapshot() {

        ClientProgress snapshot = new ClientProgress();
        snapshot.explorationState.putAll(explorationState);
        snapshot.visitedLocationIds.addAll(visitedLocationIds);
        return snapshot;
    }

    /**
     * Initializes textures for all exploration states.
     * Should be run at client startup when RenderSystem is available
     */
    public void initializeTextures() {

        for (PlayerExploration exploration : explorationState.values()) {
            exploration.initializeTexture();
        }
    }

    /**
     * Disposes and removes all per-dimension {@link PlayerExploration} instances
     * This essentially resets the client's exploration progress for all dimensions
     *
     * @param autoGenOnly When true, only automatically generated exploration states are reset.
     */
    public void reset(boolean autoGenOnly) {

        explorationState.entrySet().removeIf(entry -> {

            PlayerExploration exploration = entry.getValue();

            boolean shouldRemove = !autoGenOnly || exploration.isAutoGenerated();

            if (shouldRemove) {
                LOGGER.warn("Disposing exploration state for dimension {} (auto-generated: {})", entry.getKey(), exploration.isAutoGenerated());
                exploration.dispose();
            }

            return shouldRemove;
        });

        if (!autoGenOnly) {

            ArdaMapsClient.CONFIG.getLocations().forEach(location -> {
                location.setVisited(false);
                location.setExplorationState(ExplorationState.HIDDEN);
            });
        }

        initialize();

        // Reset ArdaRegions progress
        if (!autoGenOnly && ArdaMapsClient.CONFIG.isArdaRegionsAvailable() && Client.player() != null)
            Client.player().networkHandler.sendChatCommand("ardaregions resetprogress");
    }

    /**
     * Disposes and clears all locally stored progress without persistence or server-side reset side effects.
     */
    public void clearSessionState() {

        explorationState.forEach((key, exploration) -> {
            LOGGER.warn("Disposing exploration state for dimension {} on disconnect", key);
            exploration.dispose();
        });
        explorationState.clear();
        visitedLocationIds.clear();
    }

    /**
     * Initializes the exploration state for all known dimensions
     */
    private void initialize() {

        if (ArdaMapsClient.CONFIG.getDimensions().isEmpty())
            return;

        for (Dimension dimension : ArdaMapsClient.CONFIG.getDimensions()) {

            if (dimension.hasRanges()) {
                for (var range : dimension.getExplorationRanges()) {
                    String key = explorationKey(dimension.getId(), range.index());
                    if (explorationState.containsKey(key)) continue;

                    PlayerExploration exploration = PlayerExploration.create(dimension, range.index(), null);
                    this.explorationState.put(key, exploration);
                }
            } else {
                String key = explorationKey(dimension.getId(), null);
                if (explorationState.containsKey(key)) continue;

                PlayerExploration exploration = PlayerExploration.create(dimension, null);
                this.explorationState.put(key, exploration);
            }
        }
    }

    /**
     * Builds the stable key used for exploration state persistence.
     *
     * @param dimensionId The dimension ID.
     * @param rangeIndex  The range index, or null for non-ranged dimensions.
     * @return Composite exploration key.
     */
    public static String explorationKey(String dimensionId, Integer rangeIndex) {

        return rangeIndex == null ? dimensionId : dimensionId + "#" + rangeIndex;
    }

    /**
     * Migrates old single-entry exploration state for dimensions that now declare vertical ranges.
     *
     * @param dimensions Incoming dimensions from the server.
     * @return True when at least one stale bare dimension entry was removed.
     */
    public boolean migrateRangedExploration(List<Dimension> dimensions) {

        boolean migrated = false;

        for (Dimension dimension : dimensions) {
            if (!dimension.hasRanges()) continue;

            PlayerExploration stale = explorationState.remove(explorationKey(dimension.getId(), null));
            if (stale == null) continue;

            LOGGER.warn("Removing stale single exploration state for ranged dimension {}", dimension.getId());
            stale.dispose();
            migrated = true;
        }

        return migrated;
    }

    /**
     * Removes exploration entries whose persisted grid geometry no longer matches the current dimensions.
     *
     * @param dimensions Incoming dimensions from the server.
     * @return True when at least one stale grid entry was removed.
     */
    public boolean migrateGridGeometry(List<Dimension> dimensions) {

        boolean migrated = false;

        for (Dimension dimension : dimensions) {
            Iterator<Map.Entry<String, PlayerExploration>> iterator = explorationState.entrySet().iterator();

            while (iterator.hasNext()) {
                Map.Entry<String, PlayerExploration> entry = iterator.next();
                if (!isDimensionExplorationKey(entry.getKey(), dimension.getId())) continue;

                PlayerExploration exploration = entry.getValue();
                if (exploration.matches(dimension)) continue;

                LOGGER.warn("Removing stale exploration grid for dimension key {}", entry.getKey());
                iterator.remove();
                exploration.dispose();
                migrated = true;
            }
        }

        return migrated;
    }

    /**
     * Propagates revealed ranged exploration upward as visible cells for saves created before that rule existed.
     *
     * @param dimensions Incoming dimensions from the server.
     * @return True when at least one above-range cell changed.
     */
    public boolean propagateVisibleUpward(List<Dimension> dimensions) {

        boolean changed = false;

        for (Dimension dimension : dimensions) {
            if (!dimension.hasRanges()) continue;

            for (var range : dimension.getExplorationRanges()) {
                PlayerExploration source = getExplorationState(dimension.getId(), range.index(), false);
                if (source == null) continue;

                List<PlayerExploration> aboveExplorations = dimension.rangesAbove(range).stream()
                        .map(above -> getExplorationState(dimension.getId(), above.index(), false))
                        .filter(Objects::nonNull)
                        .toList();
                if (aboveExplorations.isEmpty()) continue;

                changed |= propagateVisibleCells(source, aboveExplorations);
            }
        }

        return changed;
    }

    /**
     * Propagates each revealed source cell to above-range exploration states.
     *
     * @param source            The source range exploration.
     * @param aboveExplorations Exploration states for ranges above the source range.
     * @return True when at least one target cell changed.
     */
    private boolean propagateVisibleCells(PlayerExploration source, List<PlayerExploration> aboveExplorations) {

        boolean changed = false;

        for (int cellY = 0; cellY < source.getNbCellsY(); cellY++) {
            for (int cellX = 0; cellX < source.getNbCellsX(); cellX++) {
                if (source.stateAt(cellX, cellY) != ExplorationState.REVEALED) continue;

                for (PlayerExploration aboveExploration : aboveExplorations) {
                    changed |= aboveExploration.markCellAtLeast(cellX, cellY, ExplorationState.VISIBLE, 0);
                }
            }
        }

        if (changed) {
            aboveExplorations.forEach(PlayerExploration::flushTexture);
        }

        return changed;
    }

    /**
     * Checks whether an exploration key belongs to a dimension.
     *
     * @param key         Saved exploration key.
     * @param dimensionId Configured dimension ID.
     * @return Whether the key is the bare dimension or one of its ranged entries.
     */
    private boolean isDimensionExplorationKey(String key, String dimensionId) {

        return key.equals(dimensionId) || key.startsWith(dimensionId + "#");
    }

    /**
     * Retrieves the exploration state for a specific dimension.
     *
     * @param dimensionId   The ID of the dimension to retrieve the exploration state for.
     * @param createDefault Whether to create an empty exploration state when missing.
     * @return The PlayerExploration instance for the specified dimension, or null if not found.
     */
    public PlayerExploration getExplorationState(String dimensionId, boolean createDefault) {

        return getExplorationState(dimensionId, null, createDefault);
    }

    /**
     * Retrieves the exploration state for a specific dimension/range pair.
     *
     * @param dimensionId   The ID of the dimension to retrieve the exploration state for.
     * @param rangeIndex    The range index, or null for non-ranged dimensions.
     * @param createDefault Whether to create an empty exploration state when missing.
     * @return The PlayerExploration instance for the specified dimension/range, or null if not found.
     */
    public PlayerExploration getExplorationState(String dimensionId, Integer rangeIndex, boolean createDefault) {

        if (dimensionId == null) return null;

        String resolvedDimensionId = resolveDimensionId(dimensionId);
        String key = explorationKey(resolvedDimensionId, rangeIndex);
        return createDefault ? explorationState.computeIfAbsent(key, ignored -> createExplorationState(dimensionId, rangeIndex)) : explorationState.get(key);
    }

    /**
     * Creates an exploration state when the client configuration can resolve the dimension.
     *
     * @param dimensionId The raw or configured dimension ID.
     * @param rangeIndex  The range index, or null for non-ranged dimensions.
     * @return The created exploration state, or null when config is unavailable.
     */
    private PlayerExploration createExplorationState(String dimensionId, Integer rangeIndex) {

        if (ArdaMapsClient.CONFIG == null) return null;

        return PlayerExploration.create(dimensionId, rangeIndex);
    }

    /**
     * Resolves a raw world ID to the configured dimension that owns its exploration state.
     *
     * @param dimensionId The raw or configured dimension ID.
     * @return The configured dimension ID, or the input when config is unavailable.
     */
    private String resolveDimensionId(String dimensionId) {

        if (ArdaMapsClient.CONFIG == null) return dimensionId;

        Dimension dimension = ArdaMapsClient.CONFIG.getDimension(dimensionId);

        return dimension == null ? dimensionId : dimension.getId();
    }
}
